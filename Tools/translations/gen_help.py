#!/usr/bin/env python3
"""Writes Source/ParamHelp.cpp from help_en.json (the English help text of every parameter family)."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, '..', '..'))
help_ = json.load(open(os.path.join(here, 'help_en.json'), encoding='utf-8'))
def lit(s):
    return '"' + s.encode('utf-8').decode('latin-1').encode('unicode_escape').decode('ascii').replace('"', '\\"') + '"'
out = ['// Generated by Tools/translations/gen_help.py from help_en.json - do not edit by hand.',
       '#include "ParamHelp.h"', '#include "Lang.h"', '#include <map>', '', 'namespace pyra', '{',
       'const std::map<juce::String, const char*>& paramHelpTable()', '{',
       '    static const std::map<juce::String, const char*> m {']
for k, v in help_.items():
    out.append('        { %s, %s },' % (lit(k), lit(v)))
out += ['    };', '    return m;', '}', '}', '']
open(os.path.join(root, 'Source', 'ParamHelpTable.cpp'), 'w').write('\n'.join(out))
print(len(help_), 'help texts')
