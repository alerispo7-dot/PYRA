#!/usr/bin/env python3
"""Builds Source/LangTables.cpp from the translation chunks.

keys.json      : every English string, in order (the line index in the chunks)
chunks/c*.txt  : "index|it|es|fr|de|pt"  ('=' = keep the existing Italian, '*' = same in every language)
about.json     : the ABOUT text in every language and the sample credits
"""
import json, os, glob
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, '..', '..'))
keys = json.load(open(os.path.join(here, 'keys.json'), encoding='utf-8'))
langs = ['it', 'es', 'fr', 'de', 'pt']
tables = {l: {} for l in langs}
for f in sorted(glob.glob(os.path.join(here, 'chunks', 'c*.txt'))):
    for line in open(f, encoding='utf-8'):
        line = line.rstrip('\n')
        if not line.strip(): continue
        parts = line.split('|')
        idx = int(parts[0]); key = keys[idx]
        if len(parts) == 2 and parts[1] == '*': continue
        assert len(parts) == 6, (f, line)
        for l, v in zip(langs, parts[1:]):
            if v == '=' or v == key: continue
            tables[l][key] = v
about = json.load(open(os.path.join(here, 'about.json'), encoding='utf-8'))
for l in ['es', 'fr', 'de', 'pt']:
    tables[l]['ABOUT_TEXT'] = about['about'][l]
    tables[l]['SAMPLE_CREDITS'] = about['credits'][l]

def lit(s):
    b = s.encode('utf-8')
    out = '"'
    for c in b:
        ch = chr(c)
        if ch == '"': out += '\\"'
        elif ch == '\\': out += '\\\\'
        elif ch == '\n': out += '\\n'
        elif 32 <= c < 127: out += ch
        else: out += '\\x%02x' % c + '" "'   # split so the next character is not read as part of the escape
    return out + '"'

names = {'it': 'Italian', 'es': 'Spanish', 'fr': 'French', 'de': 'German', 'pt': 'Portuguese'}
out = ['// Generated by Tools/translations/gen_lang.py - do not edit by hand.',
       '// Italian here = only the strings added after 0.7 (the older ones are in Lang.cpp / LangExtra.cpp).',
       '#include "Lang.h"', '', 'namespace pyra', '{', 'namespace lang', '{', 'namespace', '{']
for l in langs:
    out.append('    const std::map<juce::String, const char*>& %s()' % l)
    out.append('    {')
    out.append('        static const std::map<juce::String, const char*> m {')
    for k in sorted(tables[l]):
        out.append('            { juce::String::fromUTF8 (%s), %s },' % (lit(k), lit(tables[l][k])))
    out.append('        };')
    out.append('        return m;')
    out.append('    }')
out += ['}', '', 'const std::map<juce::String, const char*>& table (Language l)', '{', '    switch (l)', '    {']
for l in langs:
    out.append('        case %s: return %s();' % (names[l], l))
out += ['        default: break;', '    }', '    static const std::map<juce::String, const char*> empty;', '    return empty;', '}', '}', '}', '']
open(os.path.join(root, 'Source', 'LangTables.cpp'), 'w', encoding='utf-8').write('\n'.join(out))
print({l: len(t) for l, t in tables.items()})
